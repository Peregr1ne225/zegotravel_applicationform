import { getSupabase } from "@/lib/supabase";

const TABLE = "forms";
const FORM_COLUMNS = new Set([
	"name", "nickname", "position", "expected_salary", "moo", "road", "district",
	"amphur", "province", "postal", "phone", "line_id", "ig_id", "email", "facebook",
	"home_type", "dateofbirth", "race", "nation", "religion", "card_no", "expiration_date",
	"height", "weight", "military", "marital", "sex", "father_name", "father_age",
	"father_occupation", "mother_name", "mother_age", "mother_occupation", "spouse_name",
	"spouse_working_place", "spouse_position", "children", "children_male", "children_female",
	"sibling", "sibling_male", "sibling_female", "sibling_member", "education", "job", "address",
]);

function configurationError(error: unknown) {
	if (error instanceof Error && error.message.startsWith("Supabase is not configured")) {
		return Response.json({ error: error.message }, { status: 500 });
	}
	return null;
}

function isRecord(value: unknown): value is Record<string, unknown> {
	return typeof value === "object" && value !== null && !Array.isArray(value);
}

export async function GET(request: Request) {
	try {
		const id = new URL(request.url).searchParams.get("id");
		let query = getSupabase().from(TABLE).select("*");
		if (id) query = query.eq("id", id);

		const { data, error } = await query;
		if (error) return Response.json({ error: error.message }, { status: 400 });
		return Response.json({ data });
	} catch (error) {
		return configurationError(error) ?? Response.json({ error: "Unable to read forms" }, { status: 500 });
	}
}

export async function POST(request: Request) {
	try {
		const body: unknown = await request.json();
		if (!isRecord(body)) {
			return Response.json({ error: "Request body must be a JSON object" }, { status: 400 });
		}
		if ("id" in body) {
			return Response.json({ error: "The id field is generated by the database" }, { status: 400 });
		}
		const unknownColumns = Object.keys(body).filter((key) => !FORM_COLUMNS.has(key));
		if (unknownColumns.length) {
			return Response.json({ error: `Unknown form columns: ${unknownColumns.join(", ")}` }, { status: 400 });
		}
		const missingColumns = [...FORM_COLUMNS].filter((column) => body[column] == null);
		if (missingColumns.length) {
			return Response.json(
				{ error: `Required form columns are missing: ${missingColumns.join(", ")}` },
				{ status: 400 },
			);
		}
		if (typeof body.name !== "string" || !body.name.trim()) {
			return Response.json({ error: "The name field is required" }, { status: 400 });
		}

		const { data, error } = await getSupabase().from(TABLE).insert(body).select().single();
		if (error) return Response.json({ error: error.message }, { status: 400 });
		return Response.json({ data }, { status: 201 });
	} catch (error) {
		if (error instanceof SyntaxError) {
			return Response.json({ error: "Invalid JSON body" }, { status: 400 });
		}
		return configurationError(error) ?? Response.json({ error: "Unable to create form" }, { status: 500 });
	}
}

export async function PATCH(request: Request) {
	const id = new URL(request.url).searchParams.get("id");
	if (!id) return Response.json({ error: "An id query parameter is required" }, { status: 400 });

	try {
		const body: unknown = await request.json();
		if (!isRecord(body) || Object.keys(body).length === 0) {
			return Response.json({ error: "Request body must be a non-empty JSON object" }, { status: 400 });
		}
		if ("id" in body) {
			return Response.json({ error: "The id field cannot be changed" }, { status: 400 });
		}
		const unknownColumns = Object.keys(body).filter((key) => !FORM_COLUMNS.has(key));
		if (unknownColumns.length) {
			return Response.json({ error: `Unknown form columns: ${unknownColumns.join(", ")}` }, { status: 400 });
		}
		if (Object.values(body).some((value) => value == null)) {
			return Response.json({ error: "Form columns cannot be set to null" }, { status: 400 });
		}

		const { data, error } = await getSupabase().from(TABLE).update(body).eq("id", id).select().single();
		if (error) return Response.json({ error: error.message }, { status: 400 });
		return Response.json({ data });
	} catch (error) {
		if (error instanceof SyntaxError) {
			return Response.json({ error: "Invalid JSON body" }, { status: 400 });
		}
		return configurationError(error) ?? Response.json({ error: "Unable to update form" }, { status: 500 });
	}
}

export async function DELETE(request: Request) {
	const id = new URL(request.url).searchParams.get("id");
	if (!id) return Response.json({ error: "An id query parameter is required" }, { status: 400 });

	try {
		const { data, error } = await getSupabase().from(TABLE).delete().eq("id", id).select().single();
		if (error) return Response.json({ error: error.message }, { status: 400 });
		return Response.json({ data });
	} catch (error) {
		return configurationError(error) ?? Response.json({ error: "Unable to delete form" }, { status: 500 });
	}
}
